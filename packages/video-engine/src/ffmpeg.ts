export interface MediaInfo {
  durationSeconds: number;
  sizeBytes: number;
  formatName: string;
  video?: { codec: string; width: number; height: number; fps: number; pixFmt?: string; frames?: number };
  audio?: { codec: string; sampleRate: number; channels: number };
  subtitles: { codec: string; language?: string }[];
}

function parseRate(r: string | undefined): number {
  if (!r) return 0;
  const [a, b] = r.split("/").map(Number);
  return b ? a! / b : Number(a) || 0;
}

export async function probeMedia(file: string, signal?: AbortSignal): Promise<MediaInfo> {
  const { stdout } = await runProcess(FFPROBE_BIN, ["-v", "error", "-print_format", "json", "-show_format", "-show_streams", assertSafePath(file)], { signal });
  const data = JSON.parse(stdout) as {
    format?: { duration?: string; size?: string; format_name?: string };
    streams?: { codec_type?: string; codec_name?: string; width?: number; height?: number; avg_frame_rate?: string; r_frame_rate?: string; pix_fmt?: string; nb_frames?: string; sample_rate?: string; channels?: number; tags?: { language?: string } }[];
  };
  const v = data.streams?.find((s) => s.codec_type === "video");
  const a = data.streams?.find((s) => s.codec_type === "audio");
  return {
    durationSeconds: Number(data.format?.duration ?? 0),
    sizeBytes: Number(data.format?.size ?? fs.statSync(file).size),
    formatName: data.format?.format_name ?? "",
    video: v
      ? { codec: v.codec_name ?? "", width: v.width ?? 0, height: v.height ?? 0, fps: parseRate(v.avg_frame_rate) || parseRate(v.r_frame_rate), pixFmt: v.pix_fmt, frames: v.nb_frames ? Number(v.nb_frames) : undefined }
      : undefined,
    audio: a ? { codec: a.codec_name ?? "", sampleRate: Number(a.sample_rate ?? 0), channels: a.channels ?? 0 } : undefined,
    subtitles: (data.streams ?? []).filter((s) => s.codec_type === "subtitle").map((s) => ({ codec: s.codec_name ?? "", language: s.tags?.language })),
  };
}

export interface VideoExpectation {
  width: number;
  height: number;
  fps: number;
  durationSeconds: number;
  /** Allowed duration difference in seconds. */
  durationTolerance?: number;
  requireAudio: boolean;
  requireSubtitleTrack?: boolean;
}

export interface ValidationReport {
  ok: boolean;
  issues: string[];
  info?: MediaInfo;
}

/** Pure check of probed metadata against expectations (unit-testable). */
export function checkMediaInfo(info: MediaInfo, e: VideoExpectation): string[] {
  const issues: string[] = [];
  if (!info.video) issues.push("No video stream.");
  else {
    if (info.video.codec !== "h264") issues.push(`Video codec is ${info.video.codec}, expected h264.`);
    if (info.video.width !== e.width || info.video.height !== e.height) issues.push(`Resolution is ${info.video.width}x${info.video.height}, expected ${e.width}x${e.height}.`);
    if (Math.abs(info.video.fps - e.fps) > 0.05) issues.push(`Frame rate is ${info.video.fps.toFixed(2)}, expected ${e.fps}.`);
    if (info.video.pixFmt && info.video.pixFmt !== "yuv420p") issues.push(`Pixel format is ${info.video.pixFmt}, expected yuv420p for player compatibility.`);
  }
  const tol = e.durationTolerance ?? Math.max(0.25, 1.5 / e.fps);
  if (Math.abs(info.durationSeconds - e.durationSeconds) > tol) issues.push(`Duration is ${info.durationSeconds.toFixed(2)}s, expected ${e.durationSeconds.toFixed(2)}s.`);
  if (e.requireAudio && !info.audio) issues.push("No audio stream.");
  if (e.requireSubtitleTrack && info.subtitles.length === 0) issues.push("No subtitle track.");
  if (info.sizeBytes <= 0) issues.push("File is empty.");
  return issues;
}

/**
 * Validate a rendered file: it must exist, probe as MP4 with the expected
 * streams and dimensions, and decode end-to-end without errors.
 */
export async function validateVideoFile(file: string, e: VideoExpectation, signal?: AbortSignal): Promise<ValidationReport> {
  if (!fs.existsSync(file)) return { ok: false, issues: ["Output file does not exist."] };
  if (fs.statSync(file).size === 0) return { ok: false, issues: ["Output file is empty."] };
  let info: MediaInfo;
  try {
    info = await probeMedia(file, signal);
  } catch (err) {
    return { ok: false, issues: [`ffprobe could not read the file: ${(err as Error).message}`] };
  }
  const issues = checkMediaInfo(info, e);
  try {
    await runFfmpeg(["-hide_banner", "-v", "error", "-xerror", "-i", assertSafePath(file), "-map", "0:v:0", "-f", "null", "-"], { signal });
  } catch (err) {
    if (err instanceof CancelledError) throw err;
    issues.push(`Decoding failed: ${(err as Error).message.slice(0, 300)}`);
  }
  return { ok: issues.length === 0, issues, info };
}

/** Extract one frame as PNG (for thumbnails and visual checks). */
export function buildThumbnailArgs(video: string, atSeconds: number, output: string, width = 480): string[] {
  return ["-hide_banner", "-loglevel", "error", "-y", "-ss", Math.max(0, atSeconds).toFixed(3), "-i", assertSafePath(video), "-frames:v", "1", "-vf", `scale=${assertInt(width, 16, 4096, "width")}:-2`, assertSafePath(output)];
}
