import { spawn } from "node:child_process";
import fs from "node:fs";
import type { FrameSize } from "@atlas/shared";

/**
 * FFmpeg/ffprobe helpers. Every command is built as an argument array from
 * validated, typed values and executed without a shell, so no user text is
 * ever interpreted as shell or FFmpeg syntax. User text reaches FFmpeg only
 * inside files we write (subtitle files), never as arguments.
 */

export const FFMPEG_BIN = process.env.FFMPEG_PATH || "ffmpeg";
export const FFPROBE_BIN = process.env.FFPROBE_PATH || "ffprobe";

export class FfmpegError extends Error {
  constructor(
    message: string,
    public readonly stderrTail: string,
    public readonly exitCode: number | null,
  ) {
    super(message);
    this.name = "FfmpegError";
  }
}

export class CancelledError extends Error {
  constructor(message = "Cancelled") {
    super(message);
    this.name = "CancelledError";
  }
}

const SAFE_PATH = /^[A-Za-z0-9_./-]+$/;
/** Paths passed to FFmpeg are generated by the storage layer; reject anything unexpected. */
export function assertSafePath(p: string): string {
  if (!SAFE_PATH.test(p) || p.includes("..")) throw new Error(`Refusing unsafe media path: ${p}`);
  return p;
}

const assertInt = (n: number, min: number, max: number, name: string) => {
  if (!Number.isInteger(n) || n < min || n > max) throw new Error(`${name} must be an integer in [${min}, ${max}], got ${n}`);
  return String(n);
};
const PRESETS = new Set(["ultrafast", "superfast", "veryfast", "faster", "fast", "medium", "slow", "slower"]);

export interface SceneEncodeOptions {
  size: FrameSize;
  fps: number;
  crf: number;
  preset: string;
  output: string;
}

/** Raw RGBA frames on stdin → H.264 MP4 (no audio). */
export function buildSceneEncodeArgs(o: SceneEncodeOptions): string[] {
  if (!PRESETS.has(o.preset)) throw new Error(`Unknown x264 preset ${o.preset}`);
  return [
    "-hide_banner", "-loglevel", "error", "-y",
    "-f", "rawvideo",
    "-pix_fmt", "rgba",
    "-s", `${assertInt(o.size.width, 16, 4096, "width")}x${assertInt(o.size.height, 16, 4096, "height")}`,
    "-r", assertInt(o.fps, 1, 60, "fps"),
    "-i", "pipe:0",
    "-an",
    "-c:v", "libx264",
    "-preset", o.preset,
    "-crf", assertInt(o.crf, 0, 51, "crf"),
    "-pix_fmt", "yuv420p",
    "-g", assertInt(o.fps * 2, 2, 240, "gop"),
    "-movflags", "+faststart",
    assertSafePath(o.output),
  ];
}

/** Concatenate scene clips with identical encoding parameters (stream copy, no re-encode). */
export function buildConcatArgs(listFile: string, output: string): string[] {
  return ["-hide_banner", "-loglevel", "error", "-y", "-f", "concat", "-safe", "0", "-i", assertSafePath(listFile), "-c", "copy", "-movflags", "+faststart", assertSafePath(output)];
}

export function concatListContent(files: string[]): string {
  return files.map((f) => `file '${assertSafePath(f)}'`).join("\n") + "\n";
}

export interface AudioSegment {
  /** Narration audio for this scene, or null for silence. */
  file: string | null;
  durationSeconds: number;
}

export interface AudioMixOptions {
  segments: AudioSegment[];
  /** Procedurally generated ambience bed (brown noise + low drone), no third-party assets. */
  ambience: boolean;
  output: string;
}

/**
 * Builds the soundtrack: each scene's narration padded/trimmed to the scene
 * length, concatenated, optionally mixed with a quiet generated ambience bed,
 * then loudness-normalised to -16 LUFS. Output: 48 kHz stereo WAV.
 */
export function buildAudioMixArgs(o: AudioMixOptions): string[] {
  if (o.segments.length === 0) throw new Error("No audio segments");
  const args = ["-hide_banner", "-loglevel", "error", "-y"];
  const filters: string[] = [];
  const total = o.segments.reduce((s, x) => s + x.durationSeconds, 0);
  o.segments.forEach((seg, i) => {
    const d = seg.durationSeconds.toFixed(3);
    if (seg.file) {
      args.push("-i", assertSafePath(seg.file));
      filters.push(
        `[${i}:a]aresample=48000,aformat=sample_fmts=fltp:channel_layouts=stereo,apad,atrim=0:${d},afade=t=out:st=${Math.max(0, seg.durationSeconds - 0.15).toFixed(3)}:d=0.15[s${i}]`,
      );
    } else {
      args.push("-f", "lavfi", "-t", d, "-i", "anullsrc=r=48000:cl=stereo");
      filters.push(`[${i}:a]aformat=sample_fmts=fltp:channel_layouts=stereo[s${i}]`);
    }
  });
  filters.push(`${o.segments.map((_, i) => `[s${i}]`).join("")}concat=n=${o.segments.length}:v=0:a=1[narr]`);
  if (o.ambience) {
    const n = o.segments.length;
    args.push("-f", "lavfi", "-t", total.toFixed(3), "-i", "anoisesrc=r=48000:color=brown:amplitude=0.6:seed=7");
    args.push("-f", "lavfi", "-t", total.toFixed(3), "-i", "sine=frequency=55:sample_rate=48000");
    filters.push(
      `[${n}:a]lowpass=f=320,highpass=f=40,volume=0.07,aformat=sample_fmts=fltp:channel_layouts=stereo[noise]`,
      `[${n + 1}:a]volume=0.035,aformat=sample_fmts=fltp:channel_layouts=stereo[drone]`,
      `[noise][drone]amix=inputs=2:normalize=0,afade=t=in:d=1.5,afade=t=out:st=${Math.max(0, total - 2).toFixed(3)}:d=2[amb]`,
      `[narr][amb]amix=inputs=2:duration=first:normalize=0[mix]`,
      `[mix]loudnorm=I=-16:TP=-1.5:LRA=11,aresample=48000[aout]`,
    );
  } else {
    filters.push(`[narr]loudnorm=I=-16:TP=-1.5:LRA=11,aresample=48000[aout]`);
  }
  args.push("-filter_complex", filters.join(";"), "-map", "[aout]", "-t", total.toFixed(3), "-ac", "2", "-ar", "48000", "-c:a", "pcm_s16le", assertSafePath(o.output));
  return args;
}

export interface FinalMuxOptions {
  video: string;
  audio: string | null;
  /** ASS subtitles to burn into the picture (requires re-encoding video). */
  burnSubtitles?: { assFile: string; fontsDir: string };
  /** SRT to embed as a selectable mov_text track. */
  softSubtitles?: { srtFile: string; language: "hin" | "eng" };
  crf: number;
  preset: string;
  output: string;
  title?: string;
}

/** Escape a path for use inside an FFmpeg filter argument (filtergraph quoting). */
export function escapeFilterPath(p: string): string {
  return assertSafePath(p).replace(/\\/g, "\\\\").replace(/:/g, "\\:").replace(/'/g, "\\'");
}

export function buildFinalMuxArgs(o: FinalMuxOptions): string[] {
  if (!PRESETS.has(o.preset)) throw new Error(`Unknown x264 preset ${o.preset}`);
  const args = ["-hide_banner", "-loglevel", "error", "-y", "-i", assertSafePath(o.video)];
  let idx = 1;
  let audioIdx = -1;
  let subIdx = -1;
  if (o.audio) {
    args.push("-i", assertSafePath(o.audio));
    audioIdx = idx++;
  }
  if (o.softSubtitles) {
    args.push("-i", assertSafePath(o.softSubtitles.srtFile));
    subIdx = idx;
  }
  args.push("-map", "0:v:0");
  if (audioIdx >= 0) args.push("-map", `${audioIdx}:a:0`);
  if (subIdx >= 0) args.push("-map", `${subIdx}:s:0`);
  if (o.burnSubtitles) {
    args.push(
      "-vf",
      `subtitles=filename='${escapeFilterPath(o.burnSubtitles.assFile)}':fontsdir='${escapeFilterPath(o.burnSubtitles.fontsDir)}'`,
      "-c:v", "libx264", "-preset", o.preset, "-crf", assertInt(o.crf, 0, 51, "crf"), "-pix_fmt", "yuv420p",
    );
  } else {
    args.push("-c:v", "copy");
  }
  if (audioIdx >= 0) args.push("-c:a", "aac", "-b:a", "192k");
  if (subIdx >= 0) args.push("-c:s", "mov_text", "-metadata:s:s:0", `language=${o.softSubtitles!.language}`);
  if (o.title) args.push("-metadata", `title=${o.title.replace(/[\r\n]/g, " ").slice(0, 140)}`);
  args.push("-shortest", "-movflags", "+faststart", assertSafePath(o.output));
  return args;
}

export interface RunOptions {
  signal?: AbortSignal;
  /** Called with each chunk of stdin backpressure-aware writing; see runFfmpegWithFrames. */
  timeoutMs?: number;
}

function tail(s: string, n = 2000): string {
  return s.length > n ? s.slice(-n) : s;
}

export function runProcess(bin: string, args: string[], opts: RunOptions = {}): Promise<{ stdout: string; stderr: string }> {
  return new Promise((resolve, reject) => {
    if (opts.signal?.aborted) return reject(new CancelledError());
    const child = spawn(bin, args, { stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (d) => (stdout += d));
    child.stderr.on("data", (d) => (stderr = tail(stderr + d, 8000)));
    const onAbort = () => child.kill("SIGKILL");
    opts.signal?.addEventListener("abort", onAbort, { once: true });
    const timer = opts.timeoutMs ? setTimeout(() => child.kill("SIGKILL"), opts.timeoutMs) : undefined;
    child.on("error", (err) => {
      clearTimeout(timer);
      opts.signal?.removeEventListener("abort", onAbort);
      reject(new FfmpegError(`Could not start ${bin}: ${err.message}. Is it installed and on PATH?`, "", null));
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      opts.signal?.removeEventListener("abort", onAbort);
      if (opts.signal?.aborted) return reject(new CancelledError());
      if (code === 0) resolve({ stdout, stderr });
      else reject(new FfmpegError(`${bin} exited with code ${code}: ${tail(stderr, 600).trim()}`, tail(stderr), code));
    });
  });
}

export function runFfmpeg(args: string[], opts: RunOptions = {}) {
  return runProcess(FFMPEG_BIN, args, opts);
}

/**
 * Spawn FFmpeg reading raw frames from stdin. Returns a writer that respects
 * backpressure, and a promise for process completion.
 */
export function spawnFrameEncoder(args: string[], signal?: AbortSignal) {
  const child = spawn(FFMPEG_BIN, args, { stdio: ["pipe", "ignore", "pipe"] });
  let stderr = "";
  child.stderr.on("data", (d) => (stderr = tail(stderr + d, 8000)));
  const onAbort = () => child.kill("SIGKILL");
  signal?.addEventListener("abort", onAbort, { once: true });
  const done = new Promise<void>((resolve, reject) => {
    child.on("error", (err) => reject(new FfmpegError(`Could not start ffmpeg: ${err.message}`, "", null)));
    child.on("close", (code) => {
      signal?.removeEventListener("abort", onAbort);
      if (signal?.aborted) return reject(new CancelledError());
      if (code === 0) resolve();
      else reject(new FfmpegError(`ffmpeg encoder exited with code ${code}: ${tail(stderr, 600).trim()}`, tail(stderr), code));
    });
  });
  // Keep an unhandled rejection from crashing the process if the caller fails before awaiting.
  done.catch(() => undefined);
  child.stdin.on("error", () => undefined);
  return {
    async write(buf: Buffer): Promise<void> {
      if (!child.stdin.write(buf)) {
        await new Promise<void>((res, rej) => {
          const onDrain = () => {
            child.off("close", onClose);
            res();
          };
          const onClose = () => rej(new FfmpegError(`ffmpeg closed early: ${tail(stderr, 600).trim()}`, tail(stderr), null));
          child.stdin.once("drain", onDrain);
          child.once("close", onClose);
        });
      }
    },
    async finish(): Promise<void> {
      child.stdin.end();
      await done;
    },
    kill() {
      child.kill("SIGKILL");
    },
  };
}

